#!/usr/bin/env python3
"""Local, in-memory API simulator. No provider credentials or network payments."""
import argparse
import copy
import hmac
import json
import re
import secrets
import threading
import uuid
from datetime import datetime, timedelta, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

ROOT = Path(__file__).resolve().parents[1]


def now():
    return datetime.now(timezone.utc)


def iso(value):
    return value.isoformat().replace("+00:00", "Z")


class State:
    def __init__(self):
        fixtures = ROOT / "contracts/fixtures"
        catalog = json.loads((fixtures / "catalog.json").read_text())
        self.cinemas = catalog["cinemas"]
        self.sessions = {s["id"]: s for s in catalog["sessions"]}
        tomorrow = (now() + timedelta(days=1)).replace(
            hour=12, minute=0, second=0, microsecond=0
        )
        for i, session in enumerate(self.sessions.values()):
            session["starts_at"] = iso(tomorrow + timedelta(hours=3 * i))
        self.halls = {
            hall["id"]: hall
            for hall in json.loads((fixtures / "halls.json").read_text())["items"]
        }
        self.availability = {
            item["session_id"]: item
            for item in json.loads((fixtures / "availability.json").read_text())["items"]
        }
        self.orders = {}
        self.tokens = {}
        self.keys = {}
        self.tickets = {}
        self.ticket_tokens = {}
        self.lock = threading.RLock()


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *args):
        # Do not print URLs containing mock checkout tokens.
        pass

    @property
    def state(self):
        return self.server.state

    def send(self, status, payload, content_type="application/json"):
        if content_type == "application/json":
            body = json.dumps(payload, ensure_ascii=False).encode()
        else:
            body = payload.encode()
        self.send_response(status)
        self.send_header("Content-Type", content_type + "; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("Referrer-Policy", "no-referrer")
        origin = self.headers.get("Origin", "")
        if origin in {"http://localhost:5173", "http://127.0.0.1:5173"}:
            self.send_header("Access-Control-Allow-Origin", origin)
            self.send_header("Vary", "Origin")
        self.end_headers()
        self.wfile.write(body)

    def error(self, status, code, message):
        self.send(status, {"error": {
            "code": code, "message": message, "retryable": status >= 500
        }})

    def authorized(self, order_id, token=None):
        expected = self.state.tokens.get(order_id)
        supplied = token or self.headers.get("Authorization", "").removeprefix("Bearer ")
        return bool(expected and hmac.compare_digest(expected, supplied))

    def do_OPTIONS(self):
        self.send_response(204)
        origin = self.headers.get("Origin", "")
        if origin in {"http://localhost:5173", "http://127.0.0.1:5173"}:
            self.send_header("Access-Control-Allow-Origin", origin)
            self.send_header("Vary", "Origin")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header(
            "Access-Control-Allow-Headers", "Content-Type, Authorization, Idempotency-Key"
        )
        self.send_header("Content-Length", "0")
        self.end_headers()

    def do_GET(self):
        parsed = urlparse(self.path)
        path = parsed.path
        query = parse_qs(parsed.query)
        with self.state.lock:
            if path.startswith("/__mock/pay/"):
                order_id = path.rsplit("/", 1)[-1]
                token = query.get("token", [""])[0]
                if not self.authorized(order_id, token):
                    return self.error(401, "UNAUTHORIZED", "Нет доступа к заказу")
                # IDs/tokens are generated by this server, not reflected user input.
                return self.send(200, (
                    '<!doctype html><html lang="ru"><meta charset="utf-8">'
                    '<meta name="viewport" content="width=device-width,initial-scale=1">'
                    '<title>Локальная имитация оплаты</title>'
                    '<h1>MOCK — деньги не списываются</h1>'
                    '<p>Только для разработки интерфейса.</p>'
                    '<form method="post" action="/__mock/pay/' + order_id + '">'
                    '<input type="hidden" name="token" value="' + token + '">'
                    '<button>Имитировать успешную оплату</button></form></html>'
                ), "text/html")
            if not path.startswith("/api/v1/"):
                return self.error(404, "NOT_FOUND", "Маршрут не найден")
            parts = path[len("/api/v1/"):].strip("/").split("/")
            if parts == ["health"]:
                return self.send(200, {"status": "ok", "mode": "mock", "api_version": "1.0.0"})
            if parts == ["cinemas"]:
                return self.send(200, {"items": self.state.cinemas})
            if parts == ["sessions"]:
                cinema_id = query.get("cinema_id", [""])[0]
                if not cinema_id:
                    return self.error(422, "VALIDATION_ERROR", "Нужен cinema_id")
                return self.send(200, {"items": [
                    s for s in self.state.sessions.values() if s["cinema_id"] == cinema_id
                ]})
            if len(parts) == 2 and parts[0] == "sessions":
                session = self.state.sessions.get(parts[1])
                if session:
                    return self.send(200, session)
            if len(parts) == 2 and parts[0] == "halls":
                hall = self.state.halls.get(parts[1])
                if hall:
                    return self.send(200, hall)
            if len(parts) == 3 and parts[0] == "sessions" and parts[2] == "seats":
                availability = self.state.availability.get(parts[1])
                if availability:
                    result = copy.deepcopy(availability)
                    result["updated_at"] = iso(now())
                    return self.send(200, result)
            if len(parts) in (2, 3) and parts[0] == "orders":
                order_id = parts[1]
                if not self.authorized(order_id):
                    return self.error(401, "UNAUTHORIZED", "Нет доступа к заказу")
                order = self.state.orders[order_id]
                if len(parts) == 2:
                    return self.send(200, order)
                if parts[2] == "ticket":
                    if not order["ticket_id"]:
                        return self.error(409, "TICKET_NOT_READY", "Оплата ещё не подтверждена")
                    return self.send(200, self.state.tickets[order["ticket_id"]])
            if len(parts) == 2 and parts[0] == "tickets":
                ticket_id = self.state.ticket_tokens.get(parts[1])
                if ticket_id:
                    return self.send(200, self.state.tickets[ticket_id])
            return self.error(404, "NOT_FOUND", "Объект не найден")

    def confirm(self, order_id):
        order = self.state.orders[order_id]
        if order["ticket_id"]:
            return order
        session = self.state.sessions[order["session_id"]]
        hall = self.state.halls[session["hall_id"]]
        seat = next(s for s in hall["seats"] if s["id"] == order["seat_id"])
        cinema = next(c for c in self.state.cinemas if c["id"] == session["cinema_id"])
        ticket_id = str(uuid.uuid4())
        token = secrets.token_urlsafe(32)
        ticket = {
            "id": ticket_id, "order_id": order_id, "film_title": session["movie"]["title"],
            "cinema_name": cinema["name"], "hall_name": hall["name"],
            "starts_at": session["starts_at"], "timezone": cinema["timezone"],
            "row": seat["row"], "number": seat["number"], "seat_type": seat["type"],
            "paid_minor": order["total_minor"], "currency": "RUB", "status": "valid",
            "verification_url": self.server.web_origin + "/tickets/" + token,
            "issued_at": iso(now()),
        }
        self.state.tickets[ticket_id] = ticket
        self.state.ticket_tokens[token] = ticket_id
        order.update(status="paid", ticket_id=ticket_id)
        order["payment"]["status"] = "CONFIRMED"
        for item in self.state.availability[order["session_id"]]["seats"]:
            if item["seat_id"] == order["seat_id"]:
                item["status"] = "sold"
        return order

    def do_POST(self):
        path = urlparse(self.path).path
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if not 0 < length <= 8192:
                raise ValueError()
            raw = self.rfile.read(length)
            form = self.headers.get("Content-Type", "").startswith("application/x-www-form-urlencoded")
            body = parse_qs(raw.decode()) if form else json.loads(raw)
            if not isinstance(body, dict):
                raise ValueError()
        except (ValueError, UnicodeDecodeError):
            return self.error(422, "VALIDATION_ERROR", "Некорректное тело запроса")
        with self.state.lock:
            match = re.fullmatch(r"/__mock/orders/([^/]+)/confirm", path)
            form_match = re.fullmatch(r"/__mock/pay/([^/]+)", path)
            if match or form_match:
                order_id = (match or form_match).group(1)
                token = body.get("token", [""])[0] if form_match and form else None
                if not self.authorized(order_id, token):
                    return self.error(401, "UNAUTHORIZED", "Нет доступа к заказу")
                order = self.confirm(order_id)
                if form_match:
                    self.send_response(303)
                    self.send_header("Location", self.server.web_origin + "/payment/return?order=" + order_id)
                    self.send_header("Content-Length", "0")
                    self.end_headers()
                    return
                return self.send(200, order)
            if path != "/api/v1/orders":
                return self.error(404, "NOT_FOUND", "Маршрут не найден")
            key = self.headers.get("Idempotency-Key", "")
            if not 16 <= len(key) <= 128 or set(body) != {"session_id", "seat_id", "customer_email"}:
                return self.error(422, "VALIDATION_ERROR", "Нужны ключ, матч, место и email")
            if not all(isinstance(value, str) for value in body.values()):
                return self.error(422, "VALIDATION_ERROR", "Поля должны быть строками")
            if len(body["customer_email"]) > 254 or not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", body["customer_email"]):
                return self.error(422, "VALIDATION_ERROR", "Укажите корректный email")
            canonical = json.dumps(body, sort_keys=True)
            if key in self.state.keys:
                previous_body, order_id = self.state.keys[key]
                if previous_body != canonical:
                    return self.error(409, "IDEMPOTENCY_CONFLICT", "Ключ уже использован с другим запросом")
                return self.send(200, {"order": self.state.orders[order_id], "access_token": self.state.tokens[order_id]})
            session = self.state.sessions.get(body["session_id"])
            if not session:
                return self.error(404, "NOT_FOUND", "Матч не найден")
            if datetime.fromisoformat(session["starts_at"].replace("Z", "+00:00")) <= now():
                return self.error(409, "SESSION_STARTED", "Матч уже начался")
            seat = next((s for s in self.state.availability[session["id"]]["seats"] if s["seat_id"] == body["seat_id"]), None)
            if not seat:
                return self.error(422, "VALIDATION_ERROR", "Место не принадлежит залу")
            if seat["status"] != "available":
                return self.error(409, "SEAT_UNAVAILABLE", "Это место уже заняли. Выберите другое.")
            order_id = str(uuid.uuid4())
            token = secrets.token_urlsafe(32)
            port = self.server.server_address[1]
            order = {
                "id": order_id, "session_id": session["id"], "seat_id": seat["seat_id"],
                "status": "pending_payment", "total_minor": seat["price_minor"], "currency": "RUB",
                "created_at": iso(now()), "expires_at": iso(now() + timedelta(minutes=15)),
                "payment": {"provider": "mock", "status": "PENDING",
                    "payment_url": "http://127.0.0.1:" + str(port) + "/__mock/pay/" + order_id + "?token=" + token,
                    "transaction_id": "mock_" + str(uuid.uuid4())},
                "ticket_id": None,
            }
            seat["status"] = "held"
            self.state.orders[order_id] = order
            self.state.tokens[order_id] = token
            self.state.keys[key] = (canonical, order_id)
            return self.send(201, {"order": order, "access_token": token})


def make_server(port=8000, web_origin="http://localhost:5173"):
    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    server.state = State()
    server.web_origin = web_origin.rstrip("/")
    return server


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8000)
    args = parser.parse_args()
    server = make_server(args.port)
    print("MOCK ONLY: http://127.0.0.1:" + str(args.port) + "/api/v1", flush=True)
    print("In-memory data; no real payments; restart resets orders.", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
